## Value receivers copy; pointer receivers do not

This is the decision you make on every method, and the rule is simple: if the
method changes the receiver, or the struct is large, use a pointer. Then use a
pointer for *all* of that type''s methods, so the set is consistent.

```go
package main

import "fmt"

type Counter struct{ n int }

func (c Counter) IncrementByValue()   { c.n++ }        // changes a copy: useless
func (c *Counter) IncrementByPointer() { c.n++ }       // changes the original
func (c Counter) Value() int           { return c.n }

func main() {
	c := Counter{}

	c.IncrementByValue()
	fmt.Println("after value receiver:  ", c.Value())

	c.IncrementByPointer()             // Go takes &c for you
	c.IncrementByPointer()
	fmt.Println("after pointer receiver:", c.Value())

	// The copy is real: this is the bug the value receiver hides.
	counters := []Counter{{}, {}}
	for _, counter := range counters {
		counter.IncrementByPointer()   // ranges over COPIES
	}
	fmt.Println("range over values:", counters[0].Value())

	for i := range counters {
		counters[i].IncrementByPointer()   // index into the real elements
	}
	fmt.Println("range over indexes:", counters[0].Value())
