## The collector, and what it asks of you

Go''s collector is concurrent and non-generational: it runs alongside your
program and aims for sub-millisecond pauses, at the cost of doing more total
work than a generational collector would.

```go
package main

import (
	"fmt"
	"runtime"
)

func main() {
	var before, after runtime.MemStats
	runtime.ReadMemStats(&before)

