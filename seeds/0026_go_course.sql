## The interface belongs to the consumer

This is the single biggest difference from Java or C#. Because satisfaction is
implicit, the *caller* declares the interface it needs, next to where it is
used - and the implementation package does not import it at all.

```go
package main

import (
	"errors"
	"fmt"
)

// --- the domain package would contain this -------------------------------
type Course struct {
	Slug  string
	Title string
}

var ErrNotFound = errors.New("course not found")

// The interface is declared HERE, by the code that needs it, and is as small
// as that need. The storage package never imports this one.
type CourseFinder interface {
	FindBySlug(slug string) (Course, error)
}

type Service struct {
	courses CourseFinder
}

func NewService(courses CourseFinder) *Service {
	return &Service{courses: courses}
}

func (s *Service) Describe(slug string) string {
	course, err := s.courses.FindBySlug(slug)
	if errors.Is(err, ErrNotFound) {
		return fmt.Sprintf("no course called %q", slug)
	}
	if err != nil {
		return fmt.Sprintf("could not load %q: %v", slug, err)
	}
	return "found " + course.Title
}

// --- the storage package would contain this ------------------------------
// It has no idea CourseFinder exists. It just has the method.
type InMemory struct {
	rows map[string]Course
}

func (m InMemory) FindBySlug(slug string) (Course, error) {
	course, ok := m.rows[slug]
	if !ok {
		return Course{}, fmt.Errorf("%q: %w", slug, ErrNotFound)
	}
	return course, nil
}

func main() {
	service := NewService(InMemory{rows: map[string]Course{
		"go": {Slug: "go", Title: "Go: From Basics to Expert"},
	}})

	fmt.Println(service.Describe("go"))
	fmt.Println(service.Describe("cobol"))
}
```

"Accept interfaces, return structs" is the slogan, and it follows from this: a
constructor returning a concrete type gives the caller everything, while a
parameter of interface type asks for only what is used.

