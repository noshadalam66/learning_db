## panic and recover are not exceptions

`panic` unwinds the stack and crashes the program. It is for a bug - an
impossible state, a broken invariant - not for an expected failure. `recover`
stops that unwinding, and belongs in exactly two places: the top of a server
goroutine that must not take the process down, and a package that converts a
panic back into an error at its own boundary.

