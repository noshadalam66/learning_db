Returning a pointer to a local is safe in Go - the compiler notices and
allocates accordingly. That removes a whole class of C bug, at the cost of an
allocation you might not have intended.

## What keeps memory alive

An object lives while something can reach it. Go''s characteristic leaks are a
slice that holds a much larger array, and a goroutine that never finishes.

```go
package main

import (
	"fmt"
	"runtime"
)

func main() {
	var stats runtime.MemStats

	// A small slice of a big array keeps the WHOLE array alive.
	big := make([]byte, 10_000_000)
	for i := range big {
		big[i] = byte(i)
	}
	small := big[:10]
	big = nil                          // the variable is gone; the array is not

	runtime.GC()
	runtime.ReadMemStats(&stats)
	fmt.Printf("holding %d bytes through a 10-byte slice: heap %dMB\\n",
		cap(small), stats.HeapAlloc/1_000_000)

	// copy() breaks the link, and the 10MB becomes collectable.
	independent := make([]byte, len(small))
	copy(independent, small)
	small = nil

	runtime.GC()
	runtime.ReadMemStats(&stats)
	fmt.Printf("after copying out: heap %dMB\\n", stats.HeapAlloc/1_000_000)
	fmt.Println(len(independent))
}
