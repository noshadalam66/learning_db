## Wrap with %w, and unwrap with errors.Is and errors.As

```go
package main

import (
	"errors"
	"fmt"
)

// A sentinel error: a package-level value callers can compare against.
var ErrNotFound = errors.New("not found")

// A typed error, when the caller needs detail rather than just identity.
type ValidationError struct {
	Field  string
	Reason string
}

func (e *ValidationError) Error() string {
	return fmt.Sprintf("%s %s", e.Field, e.Reason)
}

func findCourse(slug string) error {
	if slug == "" {
		return &ValidationError{Field: "slug", Reason: "must not be empty"}
	}
	if slug != "go" {
		// %w wraps: the message gains context and the original stays reachable.
		return fmt.Errorf("course %q: %w", slug, ErrNotFound)
	}
	return nil
}

func main() {
	for _, slug := range []string{"go", "cobol", ""} {
		err := findCourse(slug)

		switch {
		case err == nil:
			fmt.Printf("%-8q ok\\n", slug)

		// errors.Is walks the wrap chain looking for that exact error.
		case errors.Is(err, ErrNotFound):
			fmt.Printf("%-8q not found (full message: %v)\\n", slug, err)

		// errors.As walks it looking for a type, and fills in the target.
		default:
			var ve *ValidationError
			if errors.As(err, &ve) {
				fmt.Printf("%-8q invalid: field %s %s\\n", slug, ve.Field, ve.Reason)
			} else {
				fmt.Printf("%-8q unexpected: %v\\n", slug, err)
			}
		}
	}
}
```

Never compare with `err == ErrNotFound` once wrapping is in play - `errors.Is`
is the one that still works after a caller adds context. And never compare error
*strings*: they are for humans, and they change.

## Adding context on the way up

```go
package main

import (
	"errors"
	"fmt"
)

var ErrNoConnection = errors.New("no connection")

func query() error        { return ErrNoConnection }
func loadCourse() error {
	if err := query(); err != nil {
		return fmt.Errorf("loading course: %w", err)
	}
	return nil
}
func handleRequest() error {
	if err := loadCourse(); err != nil {
		return fmt.Errorf("GET /courses/go: %w", err)
	}
	return nil
}

func main() {
	err := handleRequest()
	fmt.Println(err)
	fmt.Println("is it ErrNoConnection?", errors.Is(err, ErrNoConnection))

	// Unwrap one layer at a time, which is what errors.Is does internally.
	for err != nil {
		fmt.Printf("  %v\\n", err)
		err = errors.Unwrap(err)
	}
}
```

Each layer adds what *it* knows and nothing more. The result reads like a path
from the request to the cause, which is exactly what you want at 3am.

## Do not ignore errors, and do not check them twice

