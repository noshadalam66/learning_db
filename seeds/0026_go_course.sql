	// for it - but it is not free, and it is the first thing to look at when
	// a Go program is slower than it should be.
	total := 0
	for i := 0; i < 1_000_000; i++ {
		s := fmt.Sprintf("item-%d", i)     // one allocation per iteration
		total += len(s)
	}

