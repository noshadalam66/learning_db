## any, type assertions and type switches

`any` (an alias for `interface{}`) holds anything. Getting the concrete value
back out is a type assertion, and the comma-ok form is the safe one.

```go
package main

import "fmt"

func main() {
	values := []any{"hello", 42, 3.5, []int{1, 2}, nil, Point{1, 2}}

	for _, v := range values {
		fmt.Println(describe(v))
	}

	// A bare assertion panics when it is wrong; the comma-ok form does not.
	var value any = "text"
	s := value.(string)
	fmt.Println(s)

	if n, ok := value.(int); ok {
		fmt.Println("an int:", n)
	} else {
		fmt.Println("not an int, and no panic")
	}
}

type Point struct{ X, Y int }

func describe(v any) string {
	switch t := v.(type) {
	case nil:
		return "nothing at all"
	case string:
		return fmt.Sprintf("a string of %d: %s", len(t), t)
	case int:
		return fmt.Sprintf("an int, doubled: %d", t*2)
	case []int:
		return fmt.Sprintf("a slice of %d ints", len(t))
	case Point:
		return fmt.Sprintf("a point at %d,%d", t.X, t.Y)
	default:
		return fmt.Sprintf("something else: %T", t)
	}
}
