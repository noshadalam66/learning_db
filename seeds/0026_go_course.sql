## Preallocate when you know the size

```go
package main

import (
	"fmt"
	"time"
)

func main() {
	const n = 5_000_000

	start := time.Now()
	grown := []int{}                     // starts at capacity 0 and keeps copying
	for i := 0; i < n; i++ {
		grown = append(grown, i)
	}
	growing := time.Since(start)

	start = time.Now()
	sized := make([]int, 0, n)           // one allocation, and no copying at all
	for i := 0; i < n; i++ {
		sized = append(sized, i)
	}
	presized := time.Since(start)

	fmt.Println("growing ", growing)
	fmt.Println("presized", presized)
	fmt.Println("same result:", len(grown) == len(sized))

	// The same applies to maps.
	start = time.Now()
	m1 := map[int]int{}
	for i := 0; i < 1_000_000; i++ {
		m1[i] = i
	}
	unsized := time.Since(start)

	start = time.Now()
	m2 := make(map[int]int, 1_000_000)
	for i := 0; i < 1_000_000; i++ {
		m2[i] = i
	}
	fmt.Println("map unsized", unsized, "presized", time.Since(start))
}
```

`append` doubles the backing array when it runs out, so growing to a million
elements copies about two million. `make([]T, 0, n)` does none of it.

