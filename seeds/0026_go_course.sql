## The deadlocks you will actually hit

```go
package main

import (
	"fmt"
	"sync"
	"time"
)

func main() {
	// 1. Sending on an unbuffered channel with no receiver ready.
	//    ch := make(chan int); ch <- 1     // fatal error: all goroutines are asleep
	//    The fix is a receiver, or a buffer.
	ch := make(chan int, 1)
	ch <- 1
	fmt.Println("buffered send did not block:", <-ch)

	// 2. Ranging over a channel nobody closes - the loop waits forever.
	//    The fix is close() in the sender, usually with defer.
	done := make(chan int, 3)
	go func() {
		defer close(done)
		for i := 0; i < 3; i++ {
			done <- i
		}
	}()
	for range done {
	}
	fmt.Println("range ended because the sender closed")

	// 3. Forgetting wg.Done, so Wait never returns. defer is the fix.
	var wg sync.WaitGroup
	wg.Add(1)
	go func() {
		defer wg.Done()                       // even if this panics
		time.Sleep(10 * time.Millisecond)
	}()
	wg.Wait()
	fmt.Println("Wait returned because Done was deferred")

	// 4. Sending to a channel whose reader has gone away. Select with a
	//    default, or a done channel, is the escape.
	orphan := make(chan int)
	select {
	case orphan <- 1:
		fmt.Println("sent")
	default:
		fmt.Println("nobody listening, and we did not block")
	}
}
