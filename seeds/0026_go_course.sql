## Embedding is composition with promotion

Embed a type and its fields and methods are promoted to the outer type. This is
not inheritance: there is no base class, no virtual dispatch, and the embedded
value is just a field with a convenient name.

```go
package main

import "fmt"

type Logger struct {
	prefix string
}

func (l Logger) Log(message string) {
	fmt.Printf("[%s] %s\\n", l.prefix, message)
}

type Job struct {
	Logger                       // embedded: no field name
	Name string
}

// The outer type can override by declaring its own method with the same name.
type QuietJob struct {
	Logger
	Name string
}

func (q QuietJob) Log(string) {}       // does nothing, deliberately

func main() {
	job := Job{Logger: Logger{prefix: "nightly"}, Name: "backup"}
	job.Log("started")                 // promoted from Logger
	job.Logger.Log("and reachable by name too")

	quiet := QuietJob{Logger: Logger{prefix: "quiet"}, Name: "silent"}
	quiet.Log("you will not see this")
	quiet.Logger.Log("but the embedded one still works")

	fmt.Println(job.Name, quiet.Name)
}
```

The important difference from inheritance: `Job` is not a `Logger` for the
purposes of dispatch. If `Logger` had a method that called `Log`, it would call
*its own* `Log`, not the outer type''s. Go has no virtual methods, and interfaces
(the next lesson) are how you get polymorphism.

