## Channels: typed pipes between goroutines

```go
package main

import "fmt"

func main() {
	// Unbuffered: a send blocks until a receive is ready, and vice versa.
	// That is a synchronisation point, not just a queue.
	messages := make(chan string)
	go func() { messages <- "from the goroutine" }()
	fmt.Println(<-messages)

	// Buffered: a send blocks only when the buffer is full.
	buffered := make(chan int, 3)
	buffered <- 1
	buffered <- 2
	fmt.Println(len(buffered), cap(buffered))
	fmt.Println(<-buffered, <-buffered)

	// Closing says "no more values". Ranging over a channel ends when it closes.
	work := make(chan int, 5)
	go func() {
		defer close(work)                    // the sender closes, never the receiver
		for i := 1; i <= 5; i++ {
			work <- i * i
		}
	}()

	total := 0
	for value := range work {
		total += value
	}
	fmt.Println("total", total)

	// Receiving from a closed channel gives the zero value immediately; the
	// comma-ok form tells you which.
	if v, ok := <-work; !ok {
