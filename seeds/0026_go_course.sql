## Strings are bytes; runes are characters

A Go string is an immutable sequence of **bytes**, usually holding UTF-8.
`len()` counts bytes. Ranging over a string yields **runes** - Unicode code
points - along with the byte offset each one started at.

```go
package main

import (
	"fmt"
	"strings"
	"unicode/utf8"
)

func main() {
	s := "héllo"

	fmt.Println(len(s))                    // 6 bytes: é takes two
	fmt.Println(utf8.RuneCountInString(s)) // 5 characters

	for i, r := range s {
		fmt.Printf("  byte %d: %c (%d)\\n", i, r, r)
	}

	fmt.Println(s[0])                      // a byte: 104
	fmt.Printf("%c\\n", []rune(s)[1])       // a rune: é

	fmt.Println(strings.ToUpper(s), strings.Contains(s, "ll"))
	fmt.Println(strings.Split("a,b,c", ","))
	fmt.Println(strings.TrimSpace("  padded  "))

	// Strings are immutable, so build with a Builder rather than +=.
	var b strings.Builder
	for i := 0; i < 5; i++ {
		fmt.Fprintf(&b, "%d,", i)
	}
	fmt.Println(b.String())
}
```

## Pointers, without the arithmetic

Go has pointers and no pointer arithmetic. `&x` takes an address, `*p` reads
through one, and the dot operator dereferences automatically.

```go
package main

import "fmt"

type Counter struct{ n int }

