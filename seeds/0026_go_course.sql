func main() {
	x := 1
	p := &x
	*p = 42
	fmt.Println(x, *p, p != nil)

	// Passing a pointer is how a function changes the caller''s value.
	double(&x)
	fmt.Println(x)

	c := Counter{}
	c.Increment()          // Go takes the address for you
	c.Increment()
	fmt.Println(c.Value())

	// new(T) allocates a zero T and returns a pointer to it.
	q := new(int)
	fmt.Println(*q)
}

func double(n *int) { *n *= 2 }
```

