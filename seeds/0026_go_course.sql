## The nil interface trap

An interface value has two parts: a type and a value. It is `nil` only when
*both* are. A nil pointer stored in an interface is therefore not a nil
interface - and this is the most notorious gotcha in the language.

```go
package main

import "fmt"

type MyError struct{ msg string }

func (e *MyError) Error() string { return e.msg }

// Broken: returning a typed nil pointer as an error.
func broken() error {
	var e *MyError = nil
	return e                        // the interface holds (*MyError, nil)
}

// Correct: return the untyped nil.
func correct() error {
	return nil
}

func main() {
	if err := broken(); err != nil {
		fmt.Printf("broken() looks like a failure: %v (type %T)\\n", err, err)
	}

	if err := correct(); err == nil {
		fmt.Println("correct() is properly nil")
	}

	fmt.Println("the rule: never declare a typed nil and return it as an interface")
}
```

