	lo, hi := values[0], values[0]
	for _, v := range values {
		if v < lo {
			lo = v
		}
		if v > hi {
			hi = v
		}
	}
	return lo, hi
}

func lookup(key string) (string, error) {
	if key != "known" {
		return "", fmt.Errorf("no value for %q", key)
	}
	return "found it", nil
}

func join(sep string, parts ...string) string {   // variadic
	return strings.Join(parts, sep)
}

