The other one - a goroutine blocked forever on a channel - was the last lesson''s
subject, and it is worth repeating here: a leaked goroutine holds its stack and
everything its closure references.

## Value or pointer: the decision you make constantly

```go
package main

import "fmt"

type Small struct{ A, B int }
type Large struct{ Data [1024]int }

// A small struct is cheaper to copy than to chase a pointer for.
func sumSmall(s Small) int { return s.A + s.B }

// A large one is not - and a pointer also avoids a copy per call.
func sumLarge(l *Large) int {
	total := 0
	for _, v := range l.Data {
		total += v
	}
	return total
}

func main() {
	small := Small{1, 2}
	large := &Large{}
	large.Data[0] = 42

	fmt.Println(sumSmall(small), sumLarge(large))

	// The rules of thumb, in order of importance:
	//   1. Use a pointer if the method must modify the receiver.
	//   2. Use a pointer if the struct contains a sync.Mutex or similar - a
	//      copy of a mutex is a different mutex, and a silent bug.
	//   3. Use a pointer for large structs; a value for small immutable ones.
	//   4. Be consistent within a type: mixing receivers confuses everyone.
	fmt.Println("copying a struct with a mutex is the one that bites silently")
}
