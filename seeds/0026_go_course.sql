## defer runs on the way out

`defer` schedules a call for when the surrounding function returns - however it
returns. It is how Go closes files, unlocks mutexes, and undoes things without a
`finally`.

```go
package main

import (
	"fmt"
	"strings"
)

func main() {
	fmt.Println(readAll("first\\nsecond\\n"))

	// Deferred calls run last-in, first-out.
	order()

	// Arguments are evaluated at the DEFER, not at the call. This catches
	// everyone once.
	x := 1
	defer fmt.Println("deferred saw x =", x)   // prints 1, not 2
	x = 2
	fmt.Println("at the end, x =", x)
}

func readAll(text string) int {
	reader := strings.NewReader(text)
	defer fmt.Println("  (reader released)")   // runs even on an early return

	count := 0
	for {
		var line string
		if _, err := fmt.Fscanln(reader, &line); err != nil {
			break
		}
		count++
	}
	return count
}

func order() {
	for i := 1; i <= 3; i++ {
		defer fmt.Println("  deferred", i)
	}
	fmt.Println("order() is returning")
}
```

## Closures capture the variable

```go
