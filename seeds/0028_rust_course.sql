    // 1. Mutating while iterating. The answer: collect what to do, then do it.
    let mut numbers = vec![1, 2, 3, 4];
    // for n in &numbers { if *n % 2 == 0 { numbers.remove(0); } }    // no
    numbers.retain(|n| n % 2 != 0);
