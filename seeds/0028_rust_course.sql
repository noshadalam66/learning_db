## The race the compiler refuses to let you write

```rust
use std::sync::{Arc, Mutex};
use std::thread;

fn main() {
    // A plain integer shared between threads does not compile:
    //   let mut counter = 0;
    //   thread::spawn(move || counter += 1);      // moves a copy - useless
    //   thread::spawn(|| counter += 1);           // borrow may outlive main
    //
    // Arc gives shared ownership across threads; Mutex gives exclusive access.
    let counter = Arc::new(Mutex::new(0));
    let mut handles = Vec::new();

    for _ in 0..8 {
        let counter = Arc::clone(&counter);
        handles.push(thread::spawn(move || {
            for _ in 0..10_000 {
                let mut value = counter.lock().expect("not poisoned");
                *value += 1;
            }   // the guard is dropped here, which unlocks - no unlock() to forget
        }));
    }

    for handle in handles {
        handle.join().unwrap();
    }

    println!("counter = {}", *counter.lock().unwrap());
    println!("exactly 80000, every single run");
}
```

`Arc` is `Rc` with an atomic count - the thread-safe version, slightly slower,
and the compiler tells you which one you needed. The `MutexGuard` unlocks when
it is dropped, so a forgotten unlock is not possible.

