## unsafe: a smaller language inside the language

`unsafe` does not turn off the borrow checker. It enables five things the
compiler cannot verify - dereferencing a raw pointer, calling an unsafe
function, implementing an unsafe trait, accessing a mutable static, and reading
a union field - and asks you to uphold the invariants yourself.

```rust
fn main() {
    let mut value = 42;

    // Creating raw pointers is safe; dereferencing them is not.
    let r1 = &value as *const i32;
    let r2 = &mut value as *mut i32;

    unsafe {
        println!("r1 points at {}", *r1);
        *r2 = 99;
    }
    println!("value is now {value}");

    // The real use: wrapping something unverifiable in a safe API. This is how
    // Vec, RefCell and every channel in the standard library are built.
    let mut data = vec![1, 2, 3, 4];
    let (left, right) = split_at_mut(&mut data, 2);
    left[0] = 10;
    right[0] = 30;
    println!("{data:?}");
}

// Safe to call, unsafe inside: the caller cannot misuse it, because the
// function guarantees the two halves do not overlap.
fn split_at_mut(values: &mut [i32], mid: usize) -> (&mut [i32], &mut [i32]) {
    let len = values.len();
    assert!(mid <= len);
    let ptr = values.as_mut_ptr();

    unsafe {
        (
            std::slice::from_raw_parts_mut(ptr, mid),
            std::slice::from_raw_parts_mut(ptr.add(mid), len - mid),
        )
    }
}
```

The discipline: keep `unsafe` blocks small, document the invariant each one
relies on, and expose a safe API around them. Most applications never write one.

