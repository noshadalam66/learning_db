## Channels: moving values between threads

```rust
use std::sync::mpsc;
use std::thread;
use std::time::Duration;

fn main() {
    // mpsc: multiple producer, single consumer.
    let (tx, rx) = mpsc::channel();

    for i in 1..=3 {
        let tx = tx.clone();
        thread::spawn(move || {
            thread::sleep(Duration::from_millis(10 * i));
            tx.send(format!("message {i}")).expect("the receiver is alive");
        });
    }

    // The original sender must be dropped, or the loop below never ends: the
    // channel closes when the LAST sender goes.
    drop(tx);

    for received in rx {
        println!("got {received}");
    }
    println!("the channel closed when every sender was dropped");
}
```

Sending **moves** the value, so the sender cannot keep using it - which is the
