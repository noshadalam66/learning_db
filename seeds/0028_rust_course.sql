## What still leaks

Rust prevents use-after-free and double-free. It does **not** prevent a leak:
forgetting a value is safe, because nothing unsafe happens as a result.

```rust
use std::cell::RefCell;
use std::rc::Rc;

struct Node {
    next: RefCell<Option<Rc<Node>>>,
}

fn main() {
    // A reference cycle. Neither count reaches zero, so neither is dropped.
    let a = Rc::new(Node { next: RefCell::new(None) });
    let b = Rc::new(Node { next: RefCell::new(None) });

    *a.next.borrow_mut() = Some(Rc::clone(&b));
    *b.next.borrow_mut() = Some(Rc::clone(&a));

    println!("a count {}, b count {}", Rc::strong_count(&a), Rc::strong_count(&b));
    println!("dropping both handles now leaks the pair - Weak is the fix");

    // And the explicit version, which is safe and occasionally what you want:
    let leaked: &''static mut String = Box::leak(Box::new(String::from("never freed")));
    println!("{leaked}");

    // Breaking the cycle by hand, so this program does not actually leak.
    *a.next.borrow_mut() = None;
    *b.next.borrow_mut() = None;
    println!("cycle broken: a count {}", Rc::strong_count(&a));
}
