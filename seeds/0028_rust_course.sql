## RefCell<T>: the borrow check, moved to runtime

`RefCell` lets you mutate through a shared reference. The rule is still one
writer or many readers - it is simply enforced at runtime, and breaking it
panics instead of failing to compile.

```rust
use std::cell::RefCell;

fn main() {
    let log = RefCell::new(Vec::<String>::new());

    // Note: `log` is not mut, yet this works.
    log.borrow_mut().push(String::from("first"));
    log.borrow_mut().push(String::from("second"));

    println!("{:?}", log.borrow());
    println!("{} entries", log.borrow().len());

    // The rule is checked at runtime. This is the panic it produces:
    let first = log.borrow();
    let second = log.try_borrow_mut();
