    let rows = HashMap::from([(
        "rust".to_string(),
        Course { slug: "rust".into(), title: "Rust: From Basics to Expert".into() },
    )]);

    let use_case = ViewCourse::new(InMemory { rows });

    for slug in ["rust", "cobol"] {
        match use_case.handle(slug) {
            Outcome::Found(course) => println!("found {} at /{}", course.title, course.slug),
            Outcome::NotFound { slug } => println!("no course called {slug}"),
        }
    }
}
