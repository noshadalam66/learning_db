## Borrowing: use without taking

A reference lets you read or modify a value without owning it. The rule the
compiler enforces: **either one mutable reference, or any number of immutable
ones - never both at once.**

```rust
fn main() {
    let mut text = String::from("hello");

    // Many readers at once is fine.
    let r1 = &text;
    let r2 = &text;
    println!("{r1} {r2} ({} chars)", length(&text));

    // One writer, and no readers while it lives.
    let w = &mut text;
    w.push_str(", world");
    println!("{w}");

    // The original owner can be used again once the borrow ends.
    println!("{text}");

    // This is what the rule prevents:
    //   let r = &text;
    //   let w = &mut text;      // error: cannot borrow as mutable
    //   println!("{r}");        // because r is still in use here
}

fn length(value: &String) -> usize {
    value.len()                     // borrowed, so the caller keeps it
}
```

That one rule eliminates data races at compile time, which is why Rust can be
concurrent without a garbage collector.

## &str and String

`String` owns a growable buffer. `&str` is a view into one - or into a literal
baked into the binary. Take `&str` in function parameters and you accept both.

```rust
fn main() {
    let owned: String = String::from("Ada Lovelace");
    let borrowed: &str = "Ada Lovelace";
    let slice: &str = &owned[0..3];

    println!("{}", greet(&owned));      // a String derefs to &str
    println!("{}", greet(borrowed));
    println!("{}", greet(slice));

    let mut building = String::new();
    for i in 1..=5 {
        building.push_str(&i.to_string());
        building.push('','');
    }
    println!("{building}");

    // Strings are UTF-8, so indexing by byte is forbidden - the compiler will
    // not let you write owned[0]. Iterate by char, or slice on a boundary.
    let unicode = "héllo";
    println!("{} bytes, {} chars", unicode.len(), unicode.chars().count());
    for (i, c) in unicode.char_indices().take(3) {
        println!("  byte {i}: {c}");
    }
}

fn greet(name: &str) -> String {
    format!("Hello, {name}")
}
```

## Numbers, and the overflow the compiler makes you handle

```rust
