pub enum Outcome {
    Found(Course),
    NotFound { slug: String },
}

// The port. Declared here, with the rules that need it.
pub trait CourseRepository {
    fn find_by_slug(&self, slug: &str) -> Option<Course>;
}

pub struct ViewCourse<R: CourseRepository> {
    courses: R,
}

impl<R: CourseRepository> ViewCourse<R> {
    pub fn new(courses: R) -> Self {
        Self { courses }
    }

    pub fn handle(&self, slug: &str) -> Outcome {
        match self.courses.find_by_slug(slug) {
            Some(course) => Outcome::Found(course),
            None => Outcome::NotFound { slug: slug.to_string() },
        }
    }
}

// --- edge -----------------------------------------------------------------
pub struct InMemory {
    rows: HashMap<String, Course>,
}

impl CourseRepository for InMemory {
    fn find_by_slug(&self, slug: &str) -> Option<Course> {
        self.rows.get(slug).cloned()
    }
}

