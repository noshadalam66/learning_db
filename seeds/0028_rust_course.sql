    // std::mem::take or replace, which swaps in the default and hands you
    // ownership of what was there.
    let mut state = State::Loaded(vec![1, 2, 3]);
    let previous = std::mem::replace(&mut state, State::Empty);
    match previous {
        State::Loaded(items) => println!("took ownership of {} items -> {state:?}", items.len()),
        State::Empty => println!("there was nothing to take"),
    }
}

