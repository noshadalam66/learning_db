## Functions, and the expression at the end

```rust
fn main() {
    println!("{}", add(2, 3));
    println!("{:?}", min_max(&[5, 2, 9, 1]));
    println!("{}", apply_twice(|n| n * 2, 3));

    let mut counter = make_counter();
    println!("{} {} {}", counter(), counter(), counter());

    // A closure that borrows, and one that takes ownership with `move`.
    let name = String::from("Ada");
    let borrowing = || println!("borrowed {name}");
    borrowing();
    println!("{name} is still usable");

    let owned = String::from("Grace");
    let taking = move || println!("owned {owned}");
    taking();
    // println!("{owned}");     // moved into the closure
}

fn add(a: i32, b: i32) -> i32 {
    a + b                         // no `return`, no semicolon
}

fn min_max(values: &[i32]) -> (i32, i32) {
    let mut lo = values[0];
    let mut hi = values[0];
    for &v in values {
        if v < lo {
            lo = v;
        }
        if v > hi {
            hi = v;
        }
    }
    (lo, hi)
}

fn apply_twice<F: Fn(i32) -> i32>(f: F, start: i32) -> i32 {
    f(f(start))
}

fn make_counter() -> impl FnMut() -> i32 {
    let mut count = 0;
    move || {
        count += 1;
        count
    }
}
```

The three closure traits say how the closure uses what it captures: `Fn` reads,
`FnMut` mutates, `FnOnce` consumes. You rarely write them by hand - the compiler
infers which one a closure is - but they appear in signatures constantly.

