## Moves: assignment gives the value away

For a type that owns memory - `String`, `Vec<T>`, a struct containing them -
assignment **moves** the value. The old name is no longer usable, which is what
makes a double free impossible.

```rust
fn main() {
    let first = String::from("hello");
    let second = first;             // moved: `first` is no longer valid

    // println!("{first}");         // error[E0382]: borrow of moved value
    println!("{second}");

    // Clone is the explicit, visible copy.
    let third = second.clone();
    println!("{second} and {third}");

    // Small types that fit in a register are Copy: assignment duplicates them.
    let a = 42;
    let b = a;
    println!("{a} {b}");            // both fine: i32 is Copy

    // Passing to a function moves too, unless the type is Copy.
    let text = String::from("given away");
    consume(text);
    // println!("{text}");          // error: value moved into consume

    let number = 7;
    consume_copy(number);
    println!("{number} is still here");
}

fn consume(value: String) {
    println!("consumed {value}");
}

fn consume_copy(value: i32) {
    println!("copied {value}");
