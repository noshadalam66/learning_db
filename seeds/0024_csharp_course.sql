    Course.cs                      public
    ICourseRepository.cs           public
    ViewCourse.cs                  public
  Omniacad.Catalogue.Sql/          an adapter. References Catalogue.
    SqlCourseRepository.cs         internal, plus one public registration method
  Omniacad.Web/                    the host. References both.
    Program.cs                     the composition root
tests/
  Omniacad.Catalogue.Tests/        fast, no database
```

The dependency arrows are enforced by the project references: `Catalogue` cannot
accidentally use EF Core, because it does not reference it. That is worth more
than any amount of documentation about layering.

