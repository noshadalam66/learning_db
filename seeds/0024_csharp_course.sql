## ref, out and in

C# lets a parameter be passed by reference, which is occasionally exactly right
and usually not.

```csharp
int value = 1;
Increment(ref value);                 // the caller''s variable is changed
Console.WriteLine(value);

if (TryParseAge("36", out int age))   // out: an extra result, not an input
{
    Console.WriteLine($"parsed {age}");
}

if (!TryParseAge("thirty", out int bad))
{
    Console.WriteLine($"could not parse, got {bad}");
}

static void Increment(ref int n) => n++;

static bool TryParseAge(string text, out int result)
    => int.TryParse(text, out result);
```

The `Try...` shape - a `bool` return and an `out` result - is how the standard
library reports an expected failure without an exception, and it is worth
copying.

