## The switch statement, and why the expression replaced it

A C# `switch` statement does not fall through - the compiler insists every
section ends with `break` or `return`. But it is still a statement: it produces
nothing, so the variable has to be declared before it and assigned inside.

```csharp
Console.WriteLine(DescribeOld(404));
Console.WriteLine(DescribeNew(404));
Console.WriteLine(DescribeNew(500));
Console.WriteLine(Categorise(15));
Console.WriteLine(Categorise(-1));

static string DescribeOld(int code)
{
    string result;
    switch (code)
    {
        case 200:
            result = "ok";
            break;
        case 301:
        case 302:
            result = "redirected";
            break;
        default:
            result = "something else";
            break;
    }
    return result;
}

// The expression form: no break, no temporary, and it produces a value.
static string DescribeNew(int code) => code switch
{
    200 => "ok",
    301 or 302 => "redirected",
    404 => "not found",
    _ => "something else",
};

// Patterns, not just constants: relational and logical patterns read like the
// rule you would say out loud.
static string Categorise(int n) => n switch
{
    < 0 => "negative",
    0 => "zero",
    > 0 and < 10 => "small",
    >= 10 and < 100 => "medium",
    _ => "large",
};
```

`_` is the discard: the catch-all arm. A switch expression with no matching arm
throws `SwitchExpressionException`, which is a loud failure rather than a silent
`null` - and over an enum or a sealed hierarchy the compiler warns when you have
missed a case.

