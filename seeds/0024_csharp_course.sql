{
    await asyncConnection.UseAsync();
}

sealed class Connection(string name) : IDisposable
{
    public void Use() => Console.WriteLine($"using {name}");
    public void Dispose() => Console.WriteLine($"disposed {name}");
}

sealed class AsyncConnection(string name) : IAsyncDisposable
{
    public async Task UseAsync()
    {
        await Task.Delay(1);
        Console.WriteLine($"using {name}");
    }

    public async ValueTask DisposeAsync()
    {
        await Task.Delay(1);
        Console.WriteLine($"disposed {name} asynchronously");
    }
}
```

A class that owns an `IDisposable` field should itself be `IDisposable` and
dispose it - the obligation travels up the ownership chain. And never write a
finaliser unless you own an unmanaged handle directly: it delays collection by a
whole generation and runs on a thread you do not control.

## Span<T>: working with memory without copying it

