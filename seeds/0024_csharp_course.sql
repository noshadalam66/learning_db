{
    public void OnChanged(string message) => Console.WriteLine($"  subscriber {id}: {message}");
}
```

The four classic sources: an event subscription never removed, a static
collection that only grows, a cached object with no eviction, and a `Timer` or
long-running task holding a closure over something large.

## IDisposable is for what the collector does not manage

The collector frees memory. It does not close a file handle, a socket, or a
database connection - those are operating-system resources with their own limits,
and the `IDisposable` pattern is how .NET releases them deterministically.

```csharp
using (var connection = new Connection("db"))
{
    connection.Use();
}
Console.WriteLine("closed at the end of the using block, not when the GC feels like it");

