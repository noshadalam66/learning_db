## The two rules that prevent most async bugs

**Never block on async code.** `.Result` and `.Wait()` deadlock in any context
with a synchronisation context (classic ASP.NET, WinForms, WPF) and waste a
thread everywhere else. Await it, all the way up.

**Do not `async void`.** Nothing can await it, so nothing can observe the
failure: an exception from an `async void` method is thrown on the thread pool
and takes the process down.

```csharp
// Right: async all the way, returning Task.
await GoodAsync();

// A fire-and-forget that at least observes its own failure.
_ = Task.Run(async () =>
{
    try
    {
        await BackgroundAsync();
    }
    catch (Exception e)
    {
        Console.WriteLine($"background failed, and we know: {e.Message}");
    }
});

await Task.Delay(100);

static async Task GoodAsync()
{
    await Task.Delay(10);
    Console.WriteLine("finished properly");
}

static async Task BackgroundAsync()
{
    await Task.Delay(10);
    throw new InvalidOperationException("something went wrong out of sight");
}
```

