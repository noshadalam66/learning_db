    try
    {
        Console.WriteLine(Load(key));
    }
    catch (ArgumentException e) when (e.ParamName == "key")
    {
        // `when` filters WITHOUT unwinding the stack, so a filter that does not
        // match leaves the exception to travel on with its original context.
        Console.WriteLine($"  bad argument: {e.Message.Split(" (")[0]}");
    }
    catch (KeyNotFoundException)
    {
        Console.WriteLine("  no such record");
    }
    finally
    {
        Console.WriteLine($"  ...done with \\"{key}\\"");
    }
}

