## LINQ is the query language, and it is lazy

`Where`, `Select` and friends build a query. Nothing runs until something
enumerates it - a `foreach`, a `ToList`, a `Count`.

```csharp
var source = new[] { 1, 2, 3, 4, 5, 6 };

var query = source
    .Where(n => { Console.WriteLine($"  testing {n}"); return n % 2 == 0; })
    .Select(n => n * n);

Console.WriteLine("nothing has run yet");
Console.WriteLine(string.Join(",", query));

// And it runs AGAIN on every enumeration - which is the trap.
Console.WriteLine($"count: {query.Count()}");

// ToList() pays for the work once.
var materialised = query.ToList();
Console.WriteLine($"{materialised.Count} without re-running anything");
