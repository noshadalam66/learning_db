## Nullable reference types: the compiler took the billion-dollar mistake away

In a modern C# project (`<Nullable>enable</Nullable>`, on by default in new
projects), `string` means "never null" and `string?` means "may be null". The
compiler tracks which is which and warns when you get it wrong.

```csharp
string certain = "always here";
string? maybe = Lookup("missing");

Console.WriteLine(certain.Length);
// Console.WriteLine(maybe.Length);   // warning: may be null here

if (maybe is not null)
{
    Console.WriteLine(maybe.Length);  // narrowed: the compiler knows it is not null
}

Console.WriteLine(maybe?.Length);                    // null-conditional
Console.WriteLine(maybe ?? "fallback");              // null-coalescing
maybe ??= "assigned now";                            // assign only if null
Console.WriteLine(maybe);

static string? Lookup(string key) => key == "known" ? "found it" : null;
```

The `!` operator - `maybe!.Length` - silences the warning without checking
anything. It is a promise to the compiler, and every one is a place the program
can throw. Prefer the check, or `??`.

