## The domain is plain C#

No framework, no attributes, nothing that needs a host to test.

```csharp
var basket = new Basket([new Money(1999), new Money(2500), new Money(1200)]);
Console.WriteLine(basket.Total);
Console.WriteLine($"free delivery: {basket.QualifiesForFreeDelivery()}");

readonly record struct Money(long Pence)
{
    public static Money operator +(Money a, Money b) => new(a.Pence + b.Pence);
    public bool IsMoreThan(Money other) => Pence > other.Pence;
    public override string ToString() => $"{Pence / 100.0:F2}";
}

sealed class Basket
{
    private readonly IReadOnlyList<Money> _lines;

    // A defensive copy: without ToList() the caller keeps a handle on the list
    // inside this object and can change it afterwards.
    public Basket(IEnumerable<Money> lines) => _lines = lines.ToList();

    public Money Total => _lines.Aggregate(new Money(0), (sum, line) => sum + line);

    public bool QualifiesForFreeDelivery() => Total.IsMoreThan(new Money(5000));
}
```

Every rule there is testable with a constructor call and an assertion - no
database, no mocks, no `WebApplicationFactory`.

## Dependencies point inward

The domain declares what it needs as an interface it owns. The implementation
lives further out and is handed in through the constructor.

```csharp
ICourseRepository repository = new InMemoryCourses(new()
{
    ["csharp"] = new Course("csharp", "C#: From Basics to Expert"),
});

var useCase = new ViewCourse(repository);

foreach (string slug in new[] { "csharp", "cobol" })
{
    string message = useCase.Handle(slug) switch
    {
        Found(var course) => $"found {course.Title}",
        NotFound(var missing) => $"no course called {missing}",
        _ => "unreachable",
    };
    Console.WriteLine(message);
}

// --- domain ---------------------------------------------------------------
record Course(string Slug, string Title);

// The port: owned by the domain, implemented at the edge. The arrow points in.
interface ICourseRepository
{
    Course? FindBySlug(string slug);
}

abstract record Outcome;
sealed record Found(Course Course) : Outcome;
sealed record NotFound(string Slug) : Outcome;

sealed class ViewCourse(ICourseRepository courses)
{
    public Outcome Handle(string slug)
        => courses.FindBySlug(slug) is { } course ? new Found(course) : new NotFound(slug);
}

// --- edge -----------------------------------------------------------------
// In production this is EF Core or Dapper. In a test it is three lines.
sealed class InMemoryCourses(Dictionary<string, Course> rows) : ICourseRepository
{
    public Course? FindBySlug(string slug) => rows.GetValueOrDefault(slug);
}
```

Three things are doing work. The repository interface is declared *with the
rules*, so the database depends on the domain rather than the other way round.
The dependency arrives through the primary constructor, so a `ViewCourse` cannot
exist in an unusable state. And the result is a type the caller must inspect,
rather than a null or an exception it may ignore.

## Projects, namespaces and what to make public

In .NET the compilation boundary is the **project**, and `internal` - the
default for a type - means "visible inside this assembly". That makes the
project the real unit of design.

```text
src/
