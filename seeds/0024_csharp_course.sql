## Why your first measurement is wrong

.NET compiles IL to machine code the first time a method runs, and tiered
compilation then recompiles the hot ones with better optimisation. Early
iterations measure the JIT, not the code.

```csharp
using System.Diagnostics;

for (int round = 1; round <= 5; round++)
{
    var clock = Stopwatch.StartNew();
    long total = 0;
    for (int i = 0; i < 5_000_000; i++) total += Work(i);
    Console.WriteLine($"round {round}: {clock.ElapsedMilliseconds}ms ({total})");
}

Console.WriteLine("the same loop five times - and the first is not like the last");

static long Work(int i) => (i % 7) * 3L;
```

Warm up before timing, run several rounds, keep the result so nothing can be
optimised away - or use **BenchmarkDotNet**, which handles warm-up, statistics
and the dead-code problem properly, and is the only thing worth quoting in an
argument.

## Measure the program, not your guess

Before optimising anything, find where the time goes: `dotnet-counters` for live
metrics, `dotnet-trace` for a profile, and the GC counters for allocation
pressure. Most "slow .NET" turns out to be an N+1 query, a lock everything
queues behind, a cache with no eviction, or an algorithm that is quadratic in
the input - none of them found by staring at the code.

## What to take away

- `StringBuilder` in a loop; `+=` on strings is quadratic.
- Boxing allocates: generics, structs and spans are how you avoid it.
- `HashSet`/`Dictionary` for membership; presize a `List<T>` when you know the size.
- LINQ costs a delegate call per element - worth it except in a hot inner loop.
- The JIT needs warm-up; use BenchmarkDotNet for anything you will act on.
- Profile first: it is usually a query, a lock, a cache, or the algorithm.
