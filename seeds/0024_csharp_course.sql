## The collector is generational

Most objects die young, and the collector is built around that. New objects go
in **gen 0**, collected often and cheaply; survivors are promoted to gen 1 and
then gen 2, which is collected rarely and expensively. Anything over about 85KB
goes straight to the **Large Object Heap**, which is not compacted by default.

```csharp
Console.WriteLine($"gen 0 collections so far: {GC.CollectionCount(0)}");

long before = GC.GetTotalMemory(false);
long checksum = 0;

for (int i = 0; i < 2_000_000; i++)
{
    var temporary = new Box(i);          // dies immediately: the cheap case
    checksum += temporary.Value;
}

Console.WriteLine($"checksum {checksum}");
Console.WriteLine($"gen 0 collections now:   {GC.CollectionCount(0)}");
Console.WriteLine($"gen 2 collections:       {GC.CollectionCount(2)}");
Console.WriteLine($"heap grew by about {(GC.GetTotalMemory(false) - before) / 1_000_000}MB");
Console.WriteLine("(indicative: the collector runs when it chooses)");

sealed class Box(int value) { public int Value { get; } = value; }
```

Two consequences. Short-lived garbage is nearly free, so contorting code to
avoid an allocation is usually not worth it. And an object that survives long
enough to reach gen 2 and then dies is the expensive case - which is exactly
what a cache with the wrong lifetime produces.

## What leaks in a language with a collector

An object is collectable when nothing can reach it. "Unreachable", not "unused",
is the rule - and every .NET leak is something still holding a reference.

```csharp
var publisher = new Publisher();

for (int i = 0; i < 3; i++)
{
    var subscriber = new Subscriber(i);
    publisher.Changed += subscriber.OnChanged;     // the publisher now holds it
}

publisher.Raise();
Console.WriteLine("three subscribers are unreachable from here - and still alive");
Console.WriteLine("because the event''s delegate list references them");

// The fix is to unsubscribe, which is what IDisposable is usually for.
var temporary = new Subscriber(99);
publisher.Changed += temporary.OnChanged;
publisher.Changed -= temporary.OnChanged;
publisher.Raise();

sealed class Publisher
{
    public event Action<string>? Changed;
    public void Raise() => Changed?.Invoke("event");
}

