Task all = Task.WhenAll(RiskyAsync(-1), RiskyAsync(-2));
try
{
    await all;
}
catch (ArgumentOutOfRangeException)
{
    Console.WriteLine($"WhenAll collected {all.Exception?.InnerExceptions.Count} failures");
}

static async Task<int> RiskyAsync(int n)
{
    await Task.Yield();
    return n < 0 ? throw new ArgumentOutOfRangeException(nameof(n)) : n * 2;
