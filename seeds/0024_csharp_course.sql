## Do not create threads by hand

`Task.Run` queues work on the thread pool, which already knows how many cores
there are. `Parallel.ForEach` and `AsParallel` go further and split a collection
across them.

```csharp
var clock = System.Diagnostics.Stopwatch.StartNew();

int[] input = Enumerable.Range(1, 12).ToArray();

// Sequential.
long sequential = input.Select(Work).Sum();
long sequentialMs = clock.ElapsedMilliseconds;

clock.Restart();

// Parallel LINQ: the same query, spread across cores.
long parallel = input.AsParallel().Select(Work).Sum();

Console.WriteLine($"sequential {sequentialMs}ms -> {sequential}");
Console.WriteLine($"parallel   {clock.ElapsedMilliseconds}ms -> {parallel}");
Console.WriteLine($"same answer: {sequential == parallel}");

static long Work(int n)
{
    long total = 0;
    for (int i = 0; i < 3_000_000; i++) total += (i % 7) * n;
    return total;
}
```

Two rules for `AsParallel` and `Parallel.ForEach`: the work must be CPU-bound
(for I/O, use `async` - a parked thread is not a busy core), and the body must
not touch shared mutable state. The second is where people come unstuck.

```csharp
// Wrong: a List<T> is not thread-safe, and this silently loses or corrupts items.
var unsafeList = new List<int>();
Parallel.For(0, 1000, i => { lock (unsafeList) { unsafeList.Add(i); } });
Console.WriteLine($"with a lock around every add: {unsafeList.Count} (correct, and slow)");

// Right: let the query build the result, with no shared state at all.
List<int> collected = Enumerable.Range(0, 1000).AsParallel().Select(i => i).ToList();
Console.WriteLine($"no sharing: {collected.Count}");

// Or use a collection designed for it.
var bag = new System.Collections.Concurrent.ConcurrentBag<int>();
Parallel.For(0, 1000, bag.Add);
Console.WriteLine($"ConcurrentBag: {bag.Count}");
```

## Channels: a queue between producers and consumers

`System.Threading.Channels` is the modern way to hand work from one part of a
program to another without sharing a collection.

```csharp
using System.Threading.Channels;

