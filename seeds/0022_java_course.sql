## Reading a Map without tripping over null

```java
import java.util.*;

public class Maps {
    public static void main(String[] args) {
        Map<String, Integer> stock = new HashMap<>(Map.of("apples", 3, "pears", 0));

        System.out.println(stock.get("apples"));
        System.out.println(stock.get("plums"));                 // null, not 0
        System.out.println(stock.getOrDefault("plums", 0));      // the safe read

        stock.putIfAbsent("apples", 99);                         // no change
        stock.merge("apples", 1, Integer::sum);                  // add to existing
        stock.computeIfAbsent("plums", key -> 0);                // insert a default

        System.out.println(stock);

        for (Map.Entry<String, Integer> entry : stock.entrySet()) {
            System.out.println(entry.getKey() + " -> " + entry.getValue());
        }

        // forEach takes the key and the value, which reads better still.
        stock.forEach((key, value) -> System.out.println(key + ": " + value));
    }
}
```

