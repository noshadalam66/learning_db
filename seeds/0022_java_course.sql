## == compares what the variable holds

For a primitive that is the value. For a reference it is the address - so `==`
on two objects asks "are these the same object?", never "do these look the
same?". `equals` is the one that asks the second question.

```java
public class Equality {
    public static void main(String[] args) {
        String a = "hello";
        String b = "hello";
        String c = new String("hello");

        System.out.println(a == b);          // true: both point at the pooled literal
        System.out.println(a == c);          // false: new String made another object
        System.out.println(a.equals(c));     // true: same characters

        // Which is why comparing strings with == works until the day it does
        // not - the day one of them is built at runtime rather than written.
        String built = "hel" + readTail();
        System.out.println(built == a);
        System.out.println(built.equals(a));
    }

    static String readTail() {
        return "lo";                 // pretend this came from a file
    }
}
```

The same trap has a boxed form. `Integer` caches -128 to 127, so `==` appears
to work on small numbers and stops working on large ones.

```java
public class Boxes {
    public static void main(String[] args) {
        Integer small1 = 100, small2 = 100;
        Integer big1 = 1000, big2 = 1000;

        System.out.println(small1 == small2);      // true - both from the cache
        System.out.println(big1 == big2);          // false - two objects
        System.out.println(big1.equals(big2));     // true - compare the values

        // Compare numbers as primitives, or with equals. Never with == on boxes.
