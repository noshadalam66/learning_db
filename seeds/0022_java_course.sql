Java splits failure into three, and the split is the lesson.

- **Checked exceptions** extend `Exception`. The compiler forces the caller to
  catch them or declare them. They are for conditions a caller can reasonably
  recover from: a missing file, a refused connection.
- **Unchecked exceptions** extend `RuntimeException`. Nothing forces anyone to
  handle them. They are for programming mistakes: a null reference, an index off
  the end, an argument that breaks a documented rule.
- **Errors** extend `Error`: `OutOfMemoryError`, `StackOverflowError`. The
  program is in trouble. Do not catch these.

