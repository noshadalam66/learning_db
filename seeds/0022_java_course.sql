## Which List, and which Map

`ArrayList` is an array that grows: indexing is instant, inserting in the middle
shifts everything after it. `LinkedList` is nodes: inserting where you already
are is instant, indexing walks the chain. In practice `ArrayList` is almost
always the right answer, because walking a chain of nodes scattered through
memory is slower than the copy you were trying to avoid.

```java
import java.util.*;

public class WhichOne {
    public static void main(String[] args) {
        Map<String, Integer> hash = new HashMap<>();      // no order at all
        Map<String, Integer> linked = new LinkedHashMap<>();   // insertion order
        Map<String, Integer> sorted = new TreeMap<>();    // sorted by key

        for (var map : List.of(hash, linked, sorted)) {
            map.put("pears", 2);
            map.put("apples", 5);
            map.put("cherries", 9);
        }

        System.out.println("HashMap:       " + hash.keySet());
