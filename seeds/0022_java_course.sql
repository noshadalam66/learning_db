## A stream describes work; it does not do it

`filter`, `map` and the rest are **intermediate** - they build a pipeline and
return immediately. Nothing runs until a **terminal** operation asks for a
result: `collect`, `forEach`, `count`, `reduce`, `findFirst`.

```java
import java.util.*;
import java.util.stream.*;

public class Lazy {
    public static void main(String[] args) {
        var numbers = List.of(1, 2, 3, 4, 5, 6);

        var pipeline = numbers.stream()
                .peek(n -> System.out.println("  looking at " + n))
                .filter(n -> n % 2 == 0)
                .map(n -> n * n);

        System.out.println("nothing has run yet");
        System.out.println(pipeline.toList());

        // Each element goes through every step before the next one starts,
        // which is what makes findFirst stop early rather than map everything.
        var first = numbers.stream()
                .peek(n -> System.out.println("  examining " + n))
                .filter(n -> n > 3)
                .findFirst();
        System.out.println(first.orElseThrow());

        // A stream is single-use. Asking twice is an error, not a re-run.
        var used = numbers.stream();
        System.out.println(used.count());
        try {
            used.count();
        } catch (IllegalStateException e) {
            System.out.println("a stream cannot be reused: " + e.getMessage());
        }
