used as a key - becomes unfindable.

```java
import java.util.*;

public class Keys {
    // A record gets equals and hashCode from its components, which is why it is
    // the right shape for a key.
    record Point(int x, int y) { }

    static final class Mutable {
        int x;
        Mutable(int x) { this.x = x; }
        @Override public boolean equals(Object o) {
            return o instanceof Mutable m && m.x == x;
        }
        @Override public int hashCode() { return Integer.hashCode(x); }
    }

    public static void main(String[] args) {
        Map<Point, String> byPoint = new HashMap<>();
        byPoint.put(new Point(1, 2), "origin-ish");
        System.out.println(byPoint.get(new Point(1, 2)));   // found: equal records

        Map<Mutable, String> byMutable = new HashMap<>();
        var key = new Mutable(1);
        byMutable.put(key, "stored");
        key.x = 2;                                          // the hash just moved
        System.out.println(byMutable.get(key));             // null - lost in the map
        System.out.println(byMutable.size());               // but still in there
    }
