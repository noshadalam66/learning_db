## try, catch, finally - and the resource problem finally solves

```java
import java.io.*;

public class Resources {
    public static void main(String[] args) {
        // try-with-resources closes everything it opened, in reverse order,
        // even when the body throws - and it does not lose the original
        // exception if closing also fails.
        try (var reader = new BufferedReader(new StringReader("first\\nsecond\\n"))) {
            String line;
            while ((line = reader.readLine()) != null) {
                System.out.println("read: " + line);
            }
        } catch (IOException e) {
            System.out.println("io: " + e.getMessage());
        }

        // The same thing written by hand, which is what everyone got wrong
        // before Java 7: the close has to be in a finally, the finally can
        // throw, and that exception replaces the interesting one.
        BufferedReader reader = null;
        try {
            reader = new BufferedReader(new StringReader("third\\n"));
            System.out.println("read: " + reader.readLine());
        } catch (IOException e) {
            System.out.println("io: " + e.getMessage());
        } finally {
            if (reader != null) {
                try {
                    reader.close();
                } catch (IOException ignored) {
                    // and here is where the real failure quietly disappears
                }
            }
        }
    }
}
