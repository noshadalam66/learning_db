## equals, hashCode and toString travel together

Two separately built objects are not equal unless the class says how to compare
them. Override `equals` and you must override `hashCode`, because every hash
collection uses the pair.

```java
import java.util.*;

public final class Money {
    private final long pence;
    private final String currency;

    public Money(long pence, String currency) {
        this.pence = pence;
        this.currency = Objects.requireNonNull(currency);
    }

    @Override
    public boolean equals(Object other) {
        if (this == other) return true;
        return other instanceof Money m && m.pence == pence && m.currency.equals(currency);
    }

    @Override
    public int hashCode() {
        return Objects.hash(pence, currency);
    }

    @Override
    public String toString() {
        return String.format("%.2f %s", pence / 100.0, currency);
    }

    public Money plus(Money other) {
        if (!other.currency.equals(currency)) {
            throw new IllegalArgumentException("cannot add " + other.currency + " to " + currency);
        }
        return new Money(pence + other.pence, currency);      // a new object
    }

    public static void main(String[] args) {
        var a = new Money(500, "GBP");
        var b = new Money(500, "GBP");

        System.out.println(a.equals(b));                       // true
        System.out.println(new HashSet<>(List.of(a, b)).size()); // 1
        System.out.println(a.plus(new Money(250, "GBP")));
    }
}
```

Skip `hashCode` and a `HashSet` keeps both objects while `equals` insists they
are the same. That bug hides for months.

