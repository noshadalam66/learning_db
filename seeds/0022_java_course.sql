## The domain is plain Java

No framework, no annotations, nothing that needs a network or a disk to test.

```java
import java.util.*;

public class Domain {
    record Money(long pence) {
        Money plus(Money other) { return new Money(pence + other.pence); }
        boolean isMoreThan(Money other) { return pence > other.pence; }
        @Override public String toString() { return String.format("%.2f", pence / 100.0); }
    }

    record Basket(List<Money> lines) {
        Basket {
            lines = List.copyOf(lines);        // defensive copy: nobody can edit it later
        }

        Money total() {
            return lines.stream().reduce(new Money(0), Money::plus);
        }

        boolean qualifiesForFreeDelivery() {
            return total().isMoreThan(new Money(5000));
        }
    }

    public static void main(String[] args) {
        var basket = new Basket(List.of(new Money(1999), new Money(2500), new Money(1200)));
        System.out.println(basket.total());
        System.out.println("free delivery: " + basket.qualifiesForFreeDelivery());
    }
}
```

Every rule there is testable with a constructor call and an assertion. No
database, no mocks, no Spring context. `List.copyOf` in the compact constructor
matters: without it a caller keeps a reference to the list inside your record
and can change it afterwards.

## Dependencies point inward

The rules declare what they need as an interface. The implementation lives
further out and is handed in - which is all "dependency injection" means, and it
needs no framework.

```java
import java.util.*;

public class Ports {
    // --- domain ---------------------------------------------------------
    record Course(String slug, String title) { }

    // The rules say what they need. They do not say where it comes from.
    interface CourseRepository {
        Optional<Course> findBySlug(String slug);
    }

    sealed interface Outcome permits Found, NotFound { }
    record Found(Course course) implements Outcome { }
    record NotFound(String slug) implements Outcome { }

    // One job, its dependencies handed in, no I/O of its own.
    static final class ViewCourse {
        private final CourseRepository courses;

        ViewCourse(CourseRepository courses) {
            this.courses = Objects.requireNonNull(courses);
        }

        Outcome handle(String slug) {
            return courses.findBySlug(slug)
                    .<Outcome>map(Found::new)
                    .orElseGet(() -> new NotFound(slug));
        }
    }

    // --- edge -----------------------------------------------------------
    // In production this talks to MySQL. In a test it is four lines.
    record InMemoryCourses(Map<String, Course> rows) implements CourseRepository {
        @Override public Optional<Course> findBySlug(String slug) {
            return Optional.ofNullable(rows.get(slug));
        }
    }

    public static void main(String[] args) {
        var useCase = new ViewCourse(new InMemoryCourses(
                Map.of("java", new Course("java", "Java: From Basics to Expert"))));

        for (String slug : List.of("java", "cobol")) {
            String message = switch (useCase.handle(slug)) {
                case Found(Course course) -> "found " + course.title();
                case NotFound(String missing) -> "no course called " + missing;
            };
            System.out.println(message);
        }
    }
}
```

Three things are doing work there. The repository is an interface *owned by the
domain*, so the database depends on the rules rather than the other way round.
The dependency arrives through the constructor, so nothing can construct a
`ViewCourse` in an unusable state. And the result is a sealed type, so "no such
course" is data the caller must handle rather than an exception it may ignore.

## Packages, and what to make public

Java''s access control works on packages, so the package is the unit of design,
not a folder to sort files into. Group by feature, not by technical layer:

```text
