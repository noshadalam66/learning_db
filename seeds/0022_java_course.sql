## Wildcards: what you can read, and what you can write

`? extends T` is a producer - you can read `T` out of it, but you cannot add,
because the actual list may be of some narrower type. `? super T` is a consumer -
you can add a `T`, but reads come back as `Object`.

```java
import java.util.*;

public class Wildcards {
    // Reads numbers. Accepts List<Integer>, List<Double>, List<Number>.
    static double total(List<? extends Number> values) {
        double sum = 0;
        for (Number value : values) sum += value.doubleValue();
        return sum;
    }

    // Writes integers. Accepts List<Integer>, List<Number>, List<Object>.
    static void addFirstThree(List<? super Integer> target) {
        target.add(1);
        target.add(2);
        target.add(3);
    }

    public static void main(String[] args) {
        System.out.println(total(List.of(1, 2, 3)));
        System.out.println(total(List.of(1.5, 2.5)));

        List<Number> numbers = new ArrayList<>();
        addFirstThree(numbers);
        System.out.println(numbers);
    }
}
```

