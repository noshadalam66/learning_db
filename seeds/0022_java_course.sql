## The old switch, and everything wrong with it

```java
public class OldSwitch {
    public static void main(String[] args) {
        System.out.println(describe(404));
        System.out.println(describe(302));      // falls through on purpose
        System.out.println(describe(500));
    }

    static String describe(int code) {
        String result;
        switch (code) {
            case 200:
                result = "ok";
                break;                 // forget this and the next case runs
            case 301:
            case 302:
                result = "redirected";
                break;
            case 404:
                result = "not found";
                break;
            default:
                result = "something else";
        }
        return result;
    }
}
```

Three problems: a missing `break` falls through silently, the variable has to be
declared before the switch and assigned inside it, and nothing checks that every
case is covered.

## The switch expression fixes all three

```java
public class NewSwitch {
    public static void main(String[] args) {
        for (int code : new int[]{200, 302, 404, 500}) {
            System.out.println(code + " -> " + describe(code));
        }
        System.out.println(season(12));
    }

    static String describe(int code) {
        return switch (code) {
            case 200 -> "ok";
            case 301, 302 -> "redirected";      // several labels, one arm
            case 404 -> "not found";
            default -> "something else";
        };
    }

    // An arm needing more than an expression uses a block and yield.
    static String season(int month) {
        return switch (month) {
            case 12, 1, 2 -> "winter";
            case 3, 4, 5 -> "spring";
            case 6, 7, 8 -> "summer";
            case 9, 10, 11 -> "autumn";
            default -> {
                var message = "no month " + month;
                yield message;
            }
        };
    }
}
```

No fall-through, it produces a value, and over an enum or a sealed type it must
cover every case or it will not compile. Level 3 builds on that.

