## Java passes everything by value - including references

This is the single most misunderstood rule in the language, and it is simple
once stated precisely: the *variable''s contents* are copied. For a primitive
that is the number. For an object that is the reference - so the method can
change the object, but cannot repoint the caller''s variable.

```java
import java.util.ArrayList;
import java.util.List;

public class PassByValue {
    public static void main(String[] args) {
        int number = 1;
        increment(number);
        System.out.println(number);            // still 1: the int was copied

        List<String> list = new ArrayList<>(List.of("a"));
        mutate(list);
        System.out.println(list);              // [a, b]: same object, changed

        reassign(list);
        System.out.println(list);              // still [a, b]: the copy was repointed
    }

    static void increment(int value) {
        value++;
    }

    static void mutate(List<String> values) {
        values.add("b");                       // reaches the caller''s object
    }

    static void reassign(List<String> values) {
        values = new ArrayList<>(List.of("z")); // only this local now points there
    }
}
```

