## Two things to know about how Dart runs

`dart run` uses the JIT: it starts quickly and optimises code that turns out to
be hot. `dart compile exe` produces an AOT binary that starts almost instantly
and has predictable performance, which is what you ship to a server. A benchmark
under one says little about the other, so measure the way you deploy.

And never benchmark a loop whose result is unused - both compilers are entitled
to notice and delete it. Print the total, add it to a counter, do something the
compiler cannot prove is pointless.

## What to take away

- `StringBuffer` or `join` for building text; `+=` in a loop is quadratic.
- A lazy `Iterable` re-runs on every pass - `toList()` when you will use it twice.
- Move invariant work out of the loop, and pick the structure: `Set` beats `List.contains`.
- `const` values are shared and cost nothing at runtime.
- `late final field = expr` is the cleanest cache Dart has.
- JIT and AOT perform differently; measure the way you deploy, and use the result.
