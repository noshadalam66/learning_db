## The dependency points inward

The rules define what they need as an interface. The implementation lives
further out and is passed in - so the application can be exercised without the
real thing.

```dart
// --- domain -------------------------------------------------------------
class Course {
  final String slug;
  final String title;
  const Course(this.slug, this.title);
}

// The rules say what they need. They do not say where it comes from.
abstract interface class CourseRepository {
  Future<Course?> findBySlug(String slug);
}

sealed class Outcome {
  const Outcome();
}

class Found extends Outcome {
  final Course course;
  const Found(this.course);
}

class NotFound extends Outcome {
  final String slug;
  const NotFound(this.slug);
}

// A use case: one job, its dependencies handed in, no I/O of its own.
class ViewCourse {
  final CourseRepository courses;
  const ViewCourse(this.courses);

  Future<Outcome> call(String slug) async {
    final course = await courses.findBySlug(slug);
    return course == null ? NotFound(slug) : Found(course);
  }
}

// --- edge ---------------------------------------------------------------
// In the real application this talks to MySQL. In a test it is three lines.
class InMemoryCourses implements CourseRepository {
  final Map<String, Course> _rows;
  const InMemoryCourses(this._rows);

  @override
  Future<Course?> findBySlug(String slug) async => _rows[slug];
}

Future<void> main() async {
  const viewCourse = ViewCourse(InMemoryCourses({
    ''dart'': Course(''dart'', ''Dart: From Basics to Expert''),
  }));

  for (final slug in [''dart'', ''cobol'']) {
    final outcome = await viewCourse(slug);
    print(switch (outcome) {
      Found(:final course) => ''found ${course.title}'',
      NotFound(:final slug) => ''no course called $slug'',
    });
  }
}
```

Three things are worth noticing. `abstract interface class` states that the type
is meant to be implemented, not extended. The use case is a class with a `call`
method, so it is invoked like a function. And the result is a sealed type rather
than a thrown exception, because "no such course" is an expected outcome, not a
bug - the caller has to handle both branches or the code does not compile.

## Files, libraries and what to export

Dart''s unit of privacy is the **library**, not the class, and by default one
file is one library. A name starting with `_` is visible everywhere in its own
library and nowhere else.

A package usually has one public file that re-exports the pieces callers should
see:

```text
lib/
  catalogue.dart          // the public face: exports the rest
  src/
    money.dart
    basket.dart
    course_repository.dart
    mysql_course_repository.dart
```

```dart
// lib/catalogue.dart - the only file a caller imports.
//
// export ''src/money.dart'';
// export ''src/basket.dart'' show Basket;
// export ''src/course_repository.dart'';
//
// src/mysql_course_repository.dart is deliberately NOT exported: it is wired up
// at the composition root and nothing else needs to name it.

void main() {
  print(''anything under src/ is private by convention, and enforced by the ''
      ''analyzer for other packages'');
}
```

Everything under `lib/src/` is private to the package as far as other packages
are concerned - the analyzer flags an import that reaches into it.

## Wire it together in exactly one place

The composition root is where the concrete choices are made: the real database,
the real clock, the real HTTP client. It is the only file that knows all of
them, and it is usually `bin/main.dart` - ten lines that build the graph and
start the thing.

Keep it dull. Anything clever there is something that cannot be tested.

## What the analyzer is for

`dart analyze` is not a linter you can ignore - it is the same front end the
