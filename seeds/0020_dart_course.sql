## Class modifiers, and the exhaustive switch they buy

Dart 3 added modifiers that state what a class permits. The most useful is
`sealed`: subclasses must live in the same library, so the compiler knows the
complete list - and a `switch` over them is checked for exhaustiveness.

```dart
sealed class Shape {
  const Shape();
}

