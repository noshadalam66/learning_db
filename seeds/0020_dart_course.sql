  print(''const identical: ${identical(a, b)}'');

  // The same class without const allocates every time.
  final c = Config(3);
  final d = Config(3);
  print(''non-const identical: ${identical(c, d)}'');

  // The same is true of collection literals, which is why const lists are
  // worth reaching for in anything that runs often.
  const list1 = [1, 2, 3];
  const list2 = [1, 2, 3];
  print(''const lists identical: ${identical(list1, list2)}'');

  // Preallocating a list of known size avoids the repeated growth of a
  // growable one.
  final clock = Stopwatch()..start();
  final grown = <int>[];
  for (var i = 0; i < 200000; i++) {
    grown.add(i);
  }
  final growing = clock.elapsedMicroseconds;

  clock.reset();
  final sized = List<int>.filled(200000, 0);
  for (var i = 0; i < 200000; i++) {
    sized[i] = i;
  }
  print(''growable ${growing}us, preallocated ${clock.elapsedMicroseconds}us'');
}
```

