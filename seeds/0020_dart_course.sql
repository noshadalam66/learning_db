## var, final and const

`var` means "infer the type", not "no type". `final` means the binding is set
once. `const` means the value is built at compile time, and the same `const`
value written twice is literally the same object.

```dart
void main() {
  var mutable = [1, 2, 3];
  mutable.add(4);              // the binding is reassignable AND the list grows

  final fixed = [1, 2, 3];
  fixed.add(4);                // fine: final stops reassignment, not mutation
  print(fixed);
  // fixed = [9];              // this would not compile

  const frozen = [1, 2, 3];
  // frozen.add(4);            // throws at runtime: a const list is immutable
  print(frozen);

  // Two const values with the same contents are one object.
  const a = [1, 2, 3];
  const b = [1, 2, 3];
  print(identical(a, b));      // true

  final c = [1, 2, 3];
  final d = [1, 2, 3];
  print(identical(c, d));      // false - two lists built at runtime
}
```

Reach for `final` by default and `const` whenever the value is known when you
write it. A `const` costs nothing at runtime and can never be mutated by
accident.

## Null safety is the type system, not a convention

In Dart, `String` cannot hold `null`. If a value may be absent its type has to
say so, with `?`. That single character is checked by the compiler, so the
class of bug where something is unexpectedly null is caught before the program
runs rather than during it.

```dart
// Returns null for a name it does not know, which is why the type says String?.
String? nickname(String name) => name == ''Ada'' ? ''the countess'' : null;

void main() {
  String certain = ''always here'';
  String? maybe = nickname(''Grace'');

  print(certain.length);
  // print(maybe.length);      // compile error: maybe can be null

  // Ask, and the compiler narrows the type inside the branch.
  if (maybe != null) {
    print(maybe.length);       // maybe is String here, not String?
  } else {
    print(''no nickname'');
  }

  // ?. skips the call and gives null instead of throwing.
  print(maybe?.length);        // null

  // ?? supplies a value when the left side is null.
  print(maybe ?? ''fallback'');

  // ??= assigns only if currently null.
  maybe ??= ''assigned now'';
  print(maybe);
}
```

## The ! operator is a promise you make to the compiler

`value!` asserts that `value` is not null. It is not a conversion and it does
not check anything at compile time - it inserts a runtime check that throws if
you were wrong.

```dart
void main() {
  Map<String, int> scores = {''ada'': 10};

  // Map lookup returns int?, because the key may be absent.
  int? direct = scores[''ada''];
  print(direct);

  // Use ! only where you can point at the reason it cannot be null.
  print(scores[''ada'']!.isEven);

  try {
    print(scores[''missing'']!.isEven);
  } on TypeError catch (e) {
    print(''threw, as promised: $e'');
  }
}
```

Every `!` is a place the program can crash. The alternative is usually shorter
anyway: `scores[''missing''] ?? 0`.

## late, and why it exists

`late` says "non-null, but not assigned yet". It moves the check from compile
time to first use, which is what you want for a field that is expensive to
build or that cannot be built in the constructor.

```dart
class Report {
  late final String summary = _build();   // runs on first read, once

  String _build() {
    print(''building...'');
    return ''the expensive summary'';
  }
}

void main() {
  final report = Report();
  print(''constructed, nothing built yet'');
  print(report.summary);
  print(report.summary);      // built once, not twice

  // A late FIELD with no initialiser is the runtime half of the feature: the
  // check happens on read. A late local is checked by the compiler instead, so
  // reading one before assigning it does not compile at all.
  final draft = Draft();
  try {
    print(draft.title);
  } on Error catch (e) {
    print(''reading before assigning: ${e.runtimeType}'');
  }
  draft.title = ''now it is set'';
  print(draft.title);
}

class Draft {
  late String title;
}
```

