## Equality is identity until you say otherwise

Two separately built objects with the same contents are not equal in Dart
unless the class says how to compare them. A value object overrides both `==`
and `hashCode` - both, always, because collections use the pair.

```dart
class Money {
  final int pence;
  final String currency;

  const Money(this.pence, this.currency);

  @override
  bool operator ==(Object other) =>
      other is Money && other.pence == pence && other.currency == currency;

  @override
  int get hashCode => Object.hash(pence, currency);

  Money operator +(Money other) {
    if (other.currency != currency) {
      throw ArgumentError(''cannot add $currency to ${other.currency}'');
    }
    return Money(pence + other.pence, currency);
  }

  @override
  String toString() => ''${(pence / 100).toStringAsFixed(2)} $currency'';
}

void main() {
  const a = Money(500, ''GBP'');
  const b = Money(500, ''GBP'');

  print(a == b);                       // true, because == was overridden
  print([a, b].toSet().length);        // 1, because hashCode agrees with ==
  print(a + const Money(250, ''GBP''));

  // const constructors also mean the two literals are one object.
  print(identical(a, b));
}
```

