## Hoisting: the work that did not need to be in the loop

```dart
void main() {
  final words = List<String>.generate(200, (i) => ''word$i'');
  final banned = List<String>.generate(200, (i) => ''word${i * 2}'');

  final clock = Stopwatch()..start();
  var slowCount = 0;
  for (final word in words) {
    if (banned.contains(word)) slowCount++;   // a scan of 200, 200 times
  }
  final slow = clock.elapsedMicroseconds;

  clock.reset();
  final bannedSet = banned.toSet();           // built once, outside the loop
  var fastCount = 0;
  for (final word in words) {
    if (bannedSet.contains(word)) fastCount++;   // a hash lookup
  }
  final fast = clock.elapsedMicroseconds;

  print(''list scan  ${slow}us ($slowCount hits)'');
  print(''set lookup ${fast}us ($fastCount hits)'');
  print(''same answer: ${slowCount == fastCount}'');
}
```

`List.contains` is a linear scan; `Set.contains` and `Map` lookup are constant
time. Choosing the right structure is worth more than any amount of
micro-tuning inside the loop.

