## switch, which is an expression too

A `switch` statement in Dart needs no `break`: cases do not fall through. Since
Dart 3 there is also a switch *expression*, which produces a value.

```dart
String describe(int code) {
  switch (code) {
    case 200:
      return ''ok'';
    case 404:
      return ''not found'';
    default:
      return ''something else'';
  }
}

// The same thing as an expression: => instead of :, commas between cases.
String describeShort(int code) => switch (code) {
      200 => ''ok'',
      404 => ''not found'',
      _ => ''something else'',
    };

void main() {
  print(describe(404));
  print(describeShort(404));
  print(describeShort(500));
}
```

The expression form has a property the statement form does not: it must produce
a value for every input, so the compiler can tell you when you have missed a
case. Level 3 uses that to make illegal states unrepresentable.

## Three kinds of parameter

```dart
// Required and positional: the order is the contract.
int add(int a, int b) => a + b;

// Optional and positional, in square brackets, with defaults.
String greet(String name, [String greeting = ''Hello'', String punctuation = ''!'']) =>
    ''$greeting, $name$punctuation'';

// Named, in braces. Optional unless marked required, and order-free.
String describe({required String name, int age = 0, String? title}) {
  final prefix = title == null ? '''' : ''$title '';
  return ''$prefix$name, $age'';
}

void main() {
  print(add(2, 3));
  print(greet(''Ada''));
  print(greet(''Ada'', ''Good morning''));
  print(describe(name: ''Ada'', age: 36));
  print(describe(age: 36, name: ''Ada'', title: ''Dr''));
}
```

The rule of thumb: positional when the meaning is obvious and there are one or
two of them, named for everything else. `draw(rect, 10, 20, true, false)` tells
a reader nothing; `draw(rect, x: 10, y: 20, filled: true, dashed: false)` does.

## Functions are values

```dart
int applyTwice(int Function(int) f, int start) => f(f(start));

void main() {
  int double(int n) => n * 2;

  print(applyTwice(double, 3));           // a named function as a value
  print(applyTwice((n) => n + 10, 3));    // an anonymous one
  print(applyTwice((int n) {              // the block form, when it needs lines
    final doubled = n * 2;
    return doubled + 1;
