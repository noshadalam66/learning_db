## Closures capture variables, not values

A function written inside another sees that function''s variables, and keeps
them alive after it returns.

```dart
Function makeCounter() {
  var count = 0;                 // one variable, captured by the closure
  return () {
    count++;
    return count;
  };
}

void main() {
  final next = makeCounter();
  print(next());                 // 1
  print(next());                 // 2

  final other = makeCounter();   // a separate call, a separate count
  print(other());                // 1

  // Each iteration of a for-in with `final` gets its own variable, so these
  // closures capture three different values rather than all seeing the last.
  final callbacks = <Function>[];
  for (final n in [1, 2, 3]) {
    callbacks.add(() => print(n));
  }
  for (final callback in callbacks) {
    callback();
  }
}
```

## Cascades, for when you are configuring one object

