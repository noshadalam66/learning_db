## An isolate is a thread with no shared memory

Each isolate has its own memory and its own event loop. Nothing is shared, so
nothing needs locking: isolates communicate by sending messages, which are
copied on the way across.

`Isolate.run` is the short version - it starts one, runs a function, returns the
result and shuts the isolate down.

```dart
